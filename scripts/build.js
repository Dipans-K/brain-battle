'use strict';
const fs = require('node:fs');
const path = require('node:path');
const url = (process.env.GAME_SERVER_URL || '').trim().replace(/\/$/, '');
if (url && !/^https?:\/\//i.test(url)) throw new Error('GAME_SERVER_URL must start with https:// (or http:// for local development).');
const config = `// Generated by scripts/build.js. Configure GAME_SERVER_URL in Netlify environment variables.\nwindow.BRAIN_BATTLE_CONFIG = { serverUrl: ${JSON.stringify(url)} };\n`;
fs.writeFileSync(path.join(__dirname, '..', 'public', 'config.js'), config);
console.log(`Built frontend config. Multiplayer server URL: ${url || '(same-origin / local development)'}`);
